"""W2 on OpenRLHF: a `--train.agent_func_path` AgentExecutor that runs each episode on the OpenEnv Harbor server TRL and
verl use (same tasks, terminus-2, local Apptainer boxes, budgets), with every model call generated by OpenRLHF's own
vLLM rollout actor (`llm_engine.generate`, token in / token out).

Why not OpenRLHF's shipped OpenAI-server executor (examples/python/agent_func_openai_server_executor.py): it re-renders
the whole chat every call and asserts that the old tokens are a prefix of the new render. Qwen3.5's template renders a
past assistant turn differently from what was sampled, so that assertion fails on the second call of every episode
(envs/openrlhf/w2_check.py). This executor keeps the README's "fully custom token-level execution" route instead
(inherit `AgentExecutorBase`, implement `execute()`) and does what MultiTurnAgentExecutor does: the episode is one
sequence, the model's sampled tokens are kept as sampled, and only each new message is tokenized and appended
(action_ranges mark the sampled tokens, so observations are context only).

How one episode runs:
  1. `execute()` starts one `run_rollout` on a Harbor server through a client subprocess in the W2 venv (OpenEnv is not
     in OpenRLHF's venv), with the engine URL pointing at this actor's proxy at a path naming the episode.
  2. terminus-2's chat calls reach the proxy; `Episode.chat` appends the new messages' tokens, generates with
     max_tokens = min(8192, 65536 - context) and returns the decoded text. A call whose prompt reaches 65536 gets
     vLLM's context-length 400, which ends the episode (summarisation off), and it is verified as-is.
  3. The verifier's score is the reward. An unscored episode gets reward 0 (OpenRLHF has no way to drop a sample from
     its group; SHARED_W2 deviation, counted in `w2_unscored`).

Also a CLI for the launcher: `python w2_agent.py data <split_dir> <out.parquet> <rows>` and `python w2_agent.py stub
<port>` (stand-in engine for the Harbor server's startup check).
"""

import asyncio
import itertools
import json
import os
import sys
import time
import uuid
from copy import deepcopy

from aiohttp import web


MAX_MODEL_LEN = int(os.environ.get("MAX_MODEL_LEN", 65536))
MAX_OUTPUT_TOKENS = 8192

# One `run_rollout` on a Harbor server, run with the W2 venv's python (same client as configs/verl/w2_agent_loop.py).
CLIENT = r"""
import json, sys
from openenv.harbor.client import HarborEnv
from termgrade_env import HARNESS, SANDBOX, RecordedHarborSession

a = json.loads(sys.argv[1])
env = HarborEnv(base_url=a["server"], max_message_size_mb=4096.0, message_timeout_s=3600.0,
                websocket_ping_interval_s=60.0, websocket_ping_timeout_s=600.0)
s = RecordedHarborSession(env=env, owns_env=True, split="", task_index=a["task_index"], instruction="", harness=HARNESS,
                          sandbox=SANDBOX, llm_url=a["llm_url"], model="policy", agent_timeout_sec=a["agent_timeout"],
                          agent_step_limit=a["step_limit"])
s.wait_for_completion()
r = s.result
print("W2RESULT " + json.dumps({"reward": r.reward if r else None, "error": r.error if r else "rollout call failed",
                                "trial": r.trial_name if r else None, "task": r.task_name if r else None}))
s.close()
"""

_episodes = {}
_proxy = {"port": None, "lock": None}
_harbor_rr = itertools.count()


def _completion(body, text, finish_reason, prompt_tokens, completion_tokens):
    return {
        "id": f"chatcmpl-{uuid.uuid4().hex}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": body.get("model", "policy"),
        "choices": [{"index": 0, "message": {"role": "assistant", "content": text}, "finish_reason": finish_reason}],
        "usage": {
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": prompt_tokens + completion_tokens,
        },
    }


async def _models(request):
    return web.json_response({"object": "list", "data": [{"id": "policy", "object": "model", "owned_by": "openrlhf"}]})


async def _chat(request):
    body = await request.json()
    episode = _episodes.get(request.match_info.get("eid"))
    # Harbor's engine probe: a tool-manifest request or a few-token "reply ok". Answered without the model.
    limit = body.get("max_tokens") or body.get("max_completion_tokens") or MAX_OUTPUT_TOKENS
    if episode is None or body.get("tools") or limit <= 16:
        return web.json_response(_completion(body, "ok", "stop", 0, 1))
    result = await episode.chat(body)
    if "error" in result:
        return web.json_response({"object": "error", **result, **result["error"]}, status=400)
    return web.json_response(result)


def _plain(message):
    content = message.get("content")
    if isinstance(content, list):
        content = "".join(part.get("text", "") for part in content if isinstance(part, dict))
    return {"role": message["role"], "content": content or ""}


class Episode:
    def __init__(self, sampling_params, max_length, hf_tokenizer, llm_engine):
        self.sampling_params, self.llm_engine = sampling_params, llm_engine
        self.max_length = min(max_length, MAX_MODEL_LEN)
        self.processor = hf_tokenizer
        self.tok = getattr(hf_tokenizer, "tokenizer", hf_tokenizer)
        self.im_end = self.tok.convert_tokens_to_ids("<|im_end|>")
        self.messages, self.ids, self.ranges, self.logprobs = [], [], [], []
        self.calls, self.non_append, self.truncated = [], 0, False

    def _render(self, messages):
        return self.processor.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True, enable_thinking=False
        )

    def _encode(self, text):
        return self.tok(text, add_special_tokens=False)["input_ids"]

    async def chat(self, body):
        messages = [_plain(m) for m in body["messages"]]
        n = len(self.messages)
        if not self.ids:
            new = self._encode(self._render(messages))
            self.logprobs = [0.0] * len(new)
        else:
            if not (len(messages) > n and messages[:n] == self.messages):
                self.non_append += 1  # never expected with summarisation off; the episode still continues as one sequence
            # Only the new messages: the text the template puts after message n-1 (the last assistant turn).
            full = self._render(messages)
            starts = [i for i in range(len(full)) if full.startswith("<|im_start|>", i)]
            text = full[starts[n] - 1 :] if len(starts) > n else full[-1:]
            if self.ids[-1] != self.im_end:  # the last call stopped on length: close its turn
                text = "<|im_end|>" + text
            new = self._encode(text)
            self.logprobs += [0.0] * len(new)
        if len(self.ids) + len(new) >= self.max_length:  # the request is refused: its messages never enter the sample
            self.logprobs = self.logprobs[: len(self.ids)]
            self.calls.append({"prompt": len(self.ids) + len(new), "completion": 0, "model_s": 0.0, "finish": "overflow"})
            msg = (
                f"This model's maximum context length is {self.max_length} tokens. However, your request has "
                f"{len(self.ids) + len(new)} input tokens. Please reduce the length of the input messages."
            )
            return {"error": {"message": msg, "type": "BadRequestError", "param": None, "code": 400}}
        self.ids = self.ids + new
        limit = body.get("max_tokens") or body.get("max_completion_tokens") or MAX_OUTPUT_TOKENS
        sp = deepcopy(self.sampling_params)
        sp.max_tokens = min(int(limit), MAX_OUTPUT_TOKENS, self.max_length - len(self.ids))
        t0 = time.time()
        out = (await self.llm_engine.generate(list(self.ids), sp)).outputs[0]
        model_s = time.time() - t0
        gen = list(out.token_ids)
        start = len(self.ids)
        self.ids = self.ids + gen
        self.ranges.append((start, len(self.ids)))
        if out.logprobs is not None:
            self.logprobs += [lp[t].logprob if t in lp else 0.0 for t, lp in zip(gen, out.logprobs)]
        else:
            self.logprobs += [0.0] * len(gen)
        self.truncated = out.finish_reason == "length"
        self.calls.append({"prompt": start, "completion": len(gen), "model_s": model_s, "finish": out.finish_reason})
        text = self.tok.decode(gen, skip_special_tokens=True)
        self.messages = messages + [{"role": "assistant", "content": text}]
        return _completion(body, text, "length" if self.truncated else "stop", start, len(gen))


async def _ensure_proxy():
    if _proxy["lock"] is None:
        _proxy["lock"] = asyncio.Lock()
    async with _proxy["lock"]:
        if _proxy["port"] is None:
            app = web.Application(client_max_size=1 << 30)
            app.router.add_get("/ep/{eid}/v1/models", _models)
            app.router.add_post("/ep/{eid}/v1/chat/completions", _chat)
            runner = web.AppRunner(app, access_log=None)
            await runner.setup()
            site = web.TCPSite(runner, "127.0.0.1", 0)
            await site.start()
            _proxy["port"] = site._server.sockets[0].getsockname()[1]
    return _proxy["port"]


try:
    from openrlhf.utils.agent import AgentExecutorBase
except ImportError:  # the `data` / `stub` CLI runs without OpenRLHF importable
    AgentExecutorBase = object


class AgentExecutor(AgentExecutorBase):
    async def execute(self, prompt, label, sampling_params, max_length, hf_tokenizer, llm_engine, images=None):
        port = await _ensure_proxy()
        eid = uuid.uuid4().hex
        ep = Episode(sampling_params, max_length, hf_tokenizer, llm_engine)
        _episodes[eid] = ep
        task_index = int(label)
        start = time.time()
        urls = [u for u in os.environ.get("HARBOR_URLS", "").split(",") if u] or [os.environ["HARBOR_URL"]]
        args = {
            "server": urls[next(_harbor_rr) % len(urls)],
            "task_index": task_index,
            "llm_url": f"http://127.0.0.1:{port}/ep/{eid}",
            "agent_timeout": float(os.environ.get("AGENT_TIMEOUT", 600)),
            "step_limit": int(os.environ.get("STEP_LIMIT", 30)),
        }
        env = dict(
            os.environ,
            PYTHONPATH=os.environ["W2_PYTHONPATH"],
            W2_EPISODES_FILE=os.path.join(os.environ["W2_EPISODES_DIR"], f"{eid}.jsonl"),
        )
        proc = await asyncio.create_subprocess_exec(
            os.environ["W2_PYTHON"], "-c", CLIENT, json.dumps(args), env=env,
            stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
        )
        try:
            out, err = await asyncio.wait_for(proc.communicate(), timeout=3600)
        except asyncio.TimeoutError:
            proc.kill()
            out, err = b"", b"client timed out after 3600 s"
        finally:
            _episodes.pop(eid, None)
        end = time.time()
        result = {"reward": None, "error": err.decode(errors="replace")[-2000:]}
        for line in out.decode(errors="replace").splitlines():
            if line.startswith("W2RESULT "):
                result = json.loads(line[len("W2RESULT ") :])
        reward = result["reward"]

        if not ep.ids:  # no model call reached the proxy: the bare instruction, no sampled tokens
            ep.ids = ep._encode(ep._render([{"role": "user", "content": prompt}]))
            ep.logprobs = [0.0] * len(ep.ids)
        model_s = sum(c["model_s"] for c in ep.calls)
        record = {
            "eid": eid, "task_index": task_index, "start": start, "end": end, "reward": reward,
            "error": result.get("error"), "trial": result.get("trial"), "task": result.get("task"),
            "calls": len(ep.calls), "model_s": model_s,
            "completion_tokens": sum(c["completion"] for c in ep.calls),
            "call_tokens_sum": sum(c["prompt"] + c["completion"] for c in ep.calls),
            "seq_tokens": len(ep.ids), "loss_tokens": sum(e - s for s, e in ep.ranges),
            "finish_reasons": [c["finish"] for c in ep.calls], "non_append": ep.non_append,
            "overflow": any(c["finish"] == "overflow" for c in ep.calls),
        }
        with open(os.path.join(os.environ["W2_EPISODES_DIR"], f"{eid}.orlhf.json"), "w") as f:
            json.dump(record, f)

        score = float(reward) if reward is not None else 0.0
        return {
            "prompt": prompt,
            "label": label,
            "images": images,
            "mm_train_inputs": None,
            "observation_tokens": ep.ids,
            "action_ranges": ep.ranges,
            "rollout_log_probs": ep.logprobs if sampling_params.logprobs is not None else None,
            "truncated": ep.truncated,
            "reward": score,
            "scores": score,
            "extra_logs": {
                "w2_unscored": float(reward is None),
                "w2_calls": float(len(ep.calls)),
                "w2_overflow": float(record["overflow"]),
                "w2_episode_s": end - start,
                "w2_model_s": model_s,
            },
        }


def _write_data(split_dir, out, rows):
    import pandas as pd

    tasks_dir = os.path.join(split_dir, "tasks")
    # The Harbor server indexes a split's tasks by sorted directory name (openenv/harbor/tasks.py).
    names = sorted(n for n in os.listdir(tasks_dir) if not n.startswith("."))
    base = [
        {"prompt": open(os.path.join(tasks_dir, n, "instruction.md")).read(), "label": str(i), "task": n}
        for i, n in enumerate(names)
    ]
    # OpenRLHF stops when the prompt pool runs out (no max-steps flag): repeat the tasks to `rows` prompts
    # (8 per step x 60 steps); its dataloader shuffles them (seed 42).
    data = [base[i % len(base)] for i in range(rows)]
    pd.DataFrame(data).to_parquet(out, index=False)
    print(f"{len(base)} tasks, {len(data)} rows -> {out}")


def _stub(port):
    app = web.Application()
    app.router.add_get("/v1/models", _models)
    app.router.add_post("/v1/chat/completions", _chat)
    web.run_app(app, host="127.0.0.1", port=port, access_log=None, print=None)


if __name__ == "__main__":
    if sys.argv[1] == "data":
        _write_data(sys.argv[2], sys.argv[3], int(sys.argv[4]))
    elif sys.argv[1] == "stub":
        _stub(int(sys.argv[2]))
