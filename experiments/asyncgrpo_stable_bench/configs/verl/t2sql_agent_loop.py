"""Text-to-SQL on verl: an AgentLoop that runs miles' episode exactly as TRL's port does
(workloads/text2sql/t2sql_episode.py, imported, not copied), with every turn generated by verl's rollout
servers.

`t2sql_episode.run_episode` owns the prompt, the SQL tool, the 5 tool turns + answer turn, the per-turn (3,072) and
per-episode (29,696) token budgets, the observation framing and the reward (incl. process penalties). This file only
supplies its `sample(prompt_ids, max_tokens)` callback through `self.server_manager.generate` (verl's load balancer,
sticky per episode, partial-rollout resume across weight syncs) and turns the episode into one verl sample:
prompt = the opening prompt, response = every later token, mask 1 on sampled tokens and 0 on observation tokens,
logprobs from vLLM. `reward_score` is the episode reward, so verl's reward manager is skipped.

The episode module imports TRL's `TurnRecord` / `Rollout` / `AsyncRolloutLoop` at the top for its TRL half. TRL is
not in verl's venv, so a stand-in module provides those names (only `TurnRecord(prompt_ids, output_ids, logprobs)` is
used by `run_episode`).

Also a CLI for the launcher: `python t2sql_agent_loop.py data <train.jsonl> <out.parquet>` writes the dataset, shuffled
with the same `datasets.Dataset.shuffle(seed=42)` as TRL's run (so both see the tasks in the same order).
"""

import collections
import json
import os
import sys
import time
import types
import uuid


if "trl.experimental.async_grpo.async_rollout_worker" not in sys.modules:
    _shim = types.ModuleType("trl.experimental.async_grpo.async_rollout_worker")
    _shim.TurnRecord = collections.namedtuple("TurnRecord", "prompt_ids output_ids logprobs")
    _shim.AsyncRolloutLoop, _shim.Rollout = object, None
    for _name in ("trl", "trl.experimental", "trl.experimental.async_grpo"):
        sys.modules.setdefault(_name, types.ModuleType(_name))
    sys.modules[_shim.__name__] = _shim

import t2sql_episode  # noqa: E402

from verl.experimental.agent_loop.agent_loop import AgentLoopBase, AgentLoopMetrics, AgentLoopOutput  # noqa: E402


# Qwen3.5 generation_config eos ids (<|im_end|>, <|endoftext|>): vLLM stops on these
STOP_IDS = {248046, 248044}
_episodes_file = None


def _log_episode(record):
    global _episodes_file
    if _episodes_file is None:
        _episodes_file = open(os.path.join(os.environ["T2SQL_EPISODES_DIR"], f"{os.getpid()}.jsonl"), "a", buffering=1)
    _episodes_file.write(json.dumps(record) + "\n")


class Text2SQLAgentLoop(AgentLoopBase):
    async def run(self, sampling_params, **kwargs):
        task = json.loads(kwargs["extra_info"]["task"])
        request_id = uuid.uuid4().hex
        steps, model_s = [], 0.0

        async def sample(prompt_ids, max_tokens):
            nonlocal model_s
            t0 = time.time()
            output = await self.server_manager.generate(
                request_id=request_id, prompt_ids=prompt_ids, sampling_params={**sampling_params, "max_tokens": max_tokens}
            )
            model_s += time.time() - t0
            steps.extend(s for s in (output.extra_fields.get("min_global_steps"), output.extra_fields.get("max_global_steps")) if s is not None)
            ids = list(output.token_ids)
            # verl reports "completed" for both vLLM stop and length; a turn that used its whole budget without a stop
            # token is a length stop
            finish = "length" if len(ids) >= max_tokens and (not ids or ids[-1] not in STOP_IDS) else "stop"
            text = self.tokenizer.decode(ids, skip_special_tokens=True)
            return ids, list(output.log_probs), text, finish

        t0 = time.time()
        result = await t2sql_episode.run_episode(sample, self.tokenizer, task, evaluation=False)
        turns = result["turns"]
        prompt_ids = list(turns[0].prompt_ids)
        response_ids, mask, logprobs = [], [], []
        for turn in turns:
            observation = turn.prompt_ids[len(prompt_ids) + len(response_ids):]
            response_ids += observation + turn.output_ids
            mask += [0] * len(observation) + [1] * len(turn.output_ids)
            logprobs += [0.0] * len(observation) + list(turn.logprobs)
        record = {
            **result["record"],
            "uid": kwargs.get("uid"),
            "start": t0,
            "end": time.time(),
            "model_s": model_s,
            "global_steps": [min(steps, default=None), max(steps, default=None)],
        }
        _log_episode(record)
        return AgentLoopOutput(
            prompt_ids=prompt_ids,
            response_ids=response_ids,
            response_mask=mask,
            response_logprobs=logprobs,
            reward_score=float(result["reward"]),
            num_turns=2 * len(turns) + 1,
            metrics=AgentLoopMetrics(generate_sequences=model_s, tool_calls=record["end"] - t0 - model_s),
            extra_fields={
                "reward_extra_info": {"correct": record["correct"], "process_penalty": record["process_penalty"]},
                "min_global_steps": min(steps, default=None),
                "max_global_steps": max(steps, default=None),
            },
        )


def _write_data(train_jsonl, out):
    import datasets

    rows = [json.loads(line) for line in open(train_jsonl)]
    # TRL's run: Dataset.from_list(...).shuffle(seed=42) (miles: --rollout-shuffle)
    ds = datasets.Dataset.from_list([{"prompt": r["prompt"], "task": r["task"], "id": r["id"]} for r in rows]).shuffle(seed=42)
    records = [
        {
            "data_source": "text2sql",
            "prompt": r["prompt"],
            "agent_name": "t2sql",
            "reward_model": {"style": "rule", "ground_truth": ""},
            "extra_info": {"index": i, "id": r["id"], "task": r["task"]},
        }
        for i, r in enumerate(ds)
    ]
    import pandas as pd

    pd.DataFrame(records).to_parquet(out, index=False)
    print(f"{len(records)} tasks -> {out} (first: {records[0]['extra_info']['id']})")


if __name__ == "__main__":
    if sys.argv[1] == "data":
        _write_data(sys.argv[2], sys.argv[3])
