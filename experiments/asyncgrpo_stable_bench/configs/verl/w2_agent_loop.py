"""W2 on verl: an AgentLoop that runs each episode on the OpenEnv Harbor server TRL uses (same tasks, terminus-2, local
Apptainer boxes, budgets), with every model call generated by verl's own rollout servers.

How one episode runs:
  1. `run()` asks a Harbor server for one `run_rollout` (terminus-2 + a box + the verifier), through a small client
     process in the W2 venv (OpenEnv is not in verl's venv). The rollout's engine URL points at this worker's proxy,
     at a path naming the episode: http://127.0.0.1:<port>/ep/<episode id>.
  2. terminus-2's chat calls reach the proxy (through Harbor's capture proxy). The proxy renders them with verl's
     Continuous Token builder (`ct_build_initial_tokens` / `ct_merge_context_msg`: earlier turns stay exactly the
     tokens the model sampled, only the new messages are tokenized), generates with `self.server_manager.generate`
     (verl's load balancer, sticky per episode, partial rollout across weight syncs) and returns the decoded text.
  3. The episode becomes one sample (prompt = first call's prompt, response = every later token, mask 1 on sampled
     tokens), as verl's ToolAgentLoop builds it. The verifier's score is `reward_score`, so verl's reward manager
     is skipped. An episode the verifier never scored returns no output: it is left out of training and of its
     group's baseline (SHARED_W2 "failed episodes").

Harbor probes each new engine URL with a few tiny requests before the agent starts; the proxy answers those without
the model, so Harbor runs the rollout at its `text` capture level (the token record is the proxy's, not Harbor's).

Also a CLI for the launcher: `python w2_agent_loop.py data <split_dir> <out.parquet>` (dataset rows, one per task in the
Harbor server's index order) and `python w2_agent_loop.py stub <port>` (a stand-in engine for the Harbor server's
startup reachability check, since verl's servers only exist once training starts).
"""

import asyncio
import itertools
import json
import os
import sys
import time
import uuid

from aiohttp import web

from verl.experimental.agent_loop.agent_loop import AgentLoopBase, AgentLoopMetrics, AgentLoopOutput


MAX_MODEL_LEN = int(os.environ.get("MAX_MODEL_LEN", 65536))
MAX_OUTPUT_TOKENS = 8192
# Episodes in flight per agent-loop worker process: verl hands each of its 8 workers one prompt (8 episodes) per batch,
# so 8 per worker keeps the whole run at <= 64 live boxes (SHARED_W2 concurrency).
SLOTS_PER_WORKER = int(os.environ.get("W2_SLOTS_PER_WORKER", 8))

# One `run_rollout` on a Harbor server, run with the W2 venv's python. Prints one W2RESULT line.
CLIENT = r"""
import json, sys
from openenv.harbor.client import HarborEnv
from termgrade_env import HARNESS, SANDBOX, RecordedHarborSession

a = json.loads(sys.argv[1])
env = HarborEnv(base_url=a["server"], max_message_size_mb=4096.0, message_timeout_s=3600.0,
                websocket_ping_interval_s=60.0, websocket_ping_timeout_s=600.0)
s = RecordedHarborSession(env=env, owns_env=True, split="", task_index=a["task_index"], instruction="", harness=HARNESS,
                          sandbox=SANDBOX, llm_url=a["llm_url"], model="policy", agent_timeout_sec=a["agent_timeout"],
                          agent_step_limit=a["step_limit"])
s.wait_for_completion()
r = s.result
print("W2RESULT " + json.dumps({"reward": r.reward if r else None, "error": r.error if r else "rollout call failed",
                                "trial": r.trial_name if r else None, "task": r.task_name if r else None}))
s.close()
"""

_episodes = {}
_proxy_port = None
_proxy_lock = None
_slots = None
_harbor_rr = itertools.count()


class ContextOverflow(Exception):
    pass


def _completion(body, text, finish_reason, prompt_tokens, completion_tokens):
    return {
        "id": f"chatcmpl-{uuid.uuid4().hex}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": body.get("model", "policy"),
        "choices": [
            {"index": 0, "message": {"role": "assistant", "content": text}, "finish_reason": finish_reason}
        ],
        "usage": {
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": prompt_tokens + completion_tokens,
        },
    }


async def _models(request):
    return web.json_response({"object": "list", "data": [{"id": "policy", "object": "model", "owned_by": "verl"}]})


async def _chat(request):
    body = await request.json()
    episode = _episodes.get(request.match_info.get("eid"))
    # Harbor's engine probe: a tool-manifest request or a few-token "reply ok". Answered without the model.
    limit = body.get("max_tokens") or body.get("max_completion_tokens") or MAX_OUTPUT_TOKENS
    if episode is None or body.get("tools") or limit <= 16:
        return web.json_response(_completion(body, "ok", "stop", 0, 1))
    try:
        return web.json_response(await episode.chat(body))
    except ContextOverflow as exc:
        # vLLM's wording, which litellm maps to a context-window error: terminus-2 (summarisation off) ends the episode.
        error = {"message": str(exc), "type": "BadRequestError", "param": None, "code": 400}
        return web.json_response({"object": "error", "error": error, **error}, status=400)


def _plain(message):
    content = message.get("content")
    if isinstance(content, list):
        content = "".join(part.get("text", "") for part in content if isinstance(part, dict))
    return {"role": message["role"], "content": content or ""}


class HarborAgentLoop(AgentLoopBase):
    async def run(self, sampling_params, **kwargs):
        global _proxy_port, _proxy_lock, _slots
        if _proxy_lock is None:
            _proxy_lock, _slots = asyncio.Lock(), asyncio.Semaphore(SLOTS_PER_WORKER)
        async with _proxy_lock:
            if _proxy_port is None:
                app = web.Application(client_max_size=1 << 30)
                app.router.add_get("/ep/{eid}/v1/models", _models)
                app.router.add_post("/ep/{eid}/v1/chat/completions", _chat)
                runner = web.AppRunner(app, access_log=None)
                await runner.setup()
                site = web.TCPSite(runner, "127.0.0.1", 0)
                await site.start()
                _proxy_port = site._server.sockets[0].getsockname()[1]

        self.sampling = dict(sampling_params)
        self.eid = uuid.uuid4().hex
        self.messages, self.ids, self.mask, self.logprobs = [], [], [], []
        self.prompt_len, self.segments, self.calls = 0, [], []
        self.global_steps, self.segment_steps = [], []
        task_index = int(kwargs["extra_info"]["task_index"])

        async with _slots:
            start = time.time()
            _episodes[self.eid] = self
            urls = [u for u in os.environ.get("HARBOR_URLS", "").split(",") if u] or [os.environ["HARBOR_URL"]]
            args = {
                "server": urls[next(_harbor_rr) % len(urls)],
                "task_index": task_index,
                "llm_url": f"http://127.0.0.1:{_proxy_port}/ep/{self.eid}",
                "agent_timeout": float(os.environ.get("AGENT_TIMEOUT", 600)),
                "step_limit": int(os.environ.get("STEP_LIMIT", 30)),
            }
            env = dict(os.environ, PYTHONPATH=os.environ["W2_PYTHONPATH"],
                       W2_EPISODES_FILE=os.path.join(os.environ["W2_EPISODES_DIR"], f"{self.eid}.jsonl"))
            proc = await asyncio.create_subprocess_exec(
                os.environ["W2_PYTHON"], "-c", CLIENT, json.dumps(args), env=env,
                stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
            )
            try:
                out, err = await asyncio.wait_for(proc.communicate(), timeout=3600)
            except asyncio.TimeoutError:
                proc.kill()
                out, err = b"", b"client timed out after 3600 s"
            finally:
                _episodes.pop(self.eid, None)
            end = time.time()

        result = {"reward": None, "error": err.decode(errors="replace")[-2000:]}
        for line in out.decode(errors="replace").splitlines():
            if line.startswith("W2RESULT "):
                result = json.loads(line[len("W2RESULT "):])
        reward = result["reward"]
        self._close_segment()
        model_s = sum(c["model_s"] for c in self.calls)
        record = {
            "eid": self.eid, "task_index": task_index, "start": start, "end": end, "reward": reward,
            "error": result.get("error"), "trial": result.get("trial"), "task": result.get("task"),
            "calls": len(self.calls), "model_s": model_s,
            "completion_tokens": sum(c["completion"] for c in self.calls),
            # SHARED_W2 trained_tokens: every call's prompt + completion, as a per-turn sample would forward them
            "call_tokens_sum": sum(c["prompt"] + c["completion"] for c in self.calls),
            "seq_tokens": self.calls[-1]["prompt"] + self.calls[-1]["completion"] if self.calls else 0,
            "samples": [{"prompt": len(p), "response": len(m), "loss_tokens": sum(m)} for p, _, m, _, _ in self.segments],
            "finish_reasons": [c["finish"] for c in self.calls],
            "overflow": any(c["finish"] == "overflow" for c in self.calls),
            "global_steps": [min(self.global_steps, default=None), max(self.global_steps, default=None)],
        }
        with open(os.path.join(os.environ["W2_EPISODES_DIR"], f"{self.eid}.verl.json"), "w") as f:
            json.dump(record, f)

        if reward is None:
            return []
        outputs = []
        for prompt_ids, response_ids, mask, logprobs, steps in self.segments:
            if sum(mask) == 0:
                continue
            outputs.append(
                AgentLoopOutput(
                    prompt_ids=prompt_ids,
                    response_ids=response_ids,
                    response_mask=mask,
                    response_logprobs=logprobs,
                    reward_score=float(reward),
                    num_turns=2 * len(self.calls) + 1,
                    metrics=AgentLoopMetrics(generate_sequences=model_s, tool_calls=end - start - model_s),
                    extra_fields={
                        "reward_extra_info": {"acc": float(reward)},
                        "min_global_steps": min(steps, default=None),
                        "max_global_steps": max(steps, default=None),
                    },
                )
            )
        return outputs

    def _close_segment(self):
        if self.ids:
            p = self.prompt_len
            self.segments.append((self.ids[:p], self.ids[p:], self.mask, self.logprobs, self.segment_steps))
        self.messages, self.ids, self.mask, self.logprobs = [], [], [], []

    async def chat(self, body):
        messages = [_plain(m) for m in body["messages"]]
        n = len(self.messages)
        appended = (
            n
            and len(messages) > n
            and messages[: n - 1] == self.messages[: n - 1]
            and messages[n - 1]["role"] == "assistant"
        )
        if appended:
            merged, mask, logprobs = await self.ct_merge_context_msg(
                messages[:n], messages, self.ids, self.mask, self.logprobs
            )
            ids = merged.token_ids
        else:
            # First call, or a history that is not an append of the last one (never seen with summarisation off):
            # the episode continues as a new sample.
            self._close_segment()
            self.segment_steps = []
            ids = await self.loop.run_in_executor(
                None, self.continuous_token_builder.build_initial_tokens, messages
            )
            mask, logprobs = [], []
            self.prompt_len = len(ids)
        if len(ids) >= MAX_MODEL_LEN:
            self.calls.append({"prompt": len(ids), "completion": 0, "model_s": 0.0, "finish": "overflow"})
            raise ContextOverflow(
                f"This model's maximum context length is {MAX_MODEL_LEN} tokens. However, your request has "
                f"{len(ids)} input tokens. Please reduce the length of the input messages."
            )
        limit = body.get("max_tokens") or body.get("max_completion_tokens") or MAX_OUTPUT_TOKENS
        max_tokens = min(int(limit), MAX_OUTPUT_TOKENS, MAX_MODEL_LEN - len(ids))
        t0 = time.time()
        output = await self.server_manager.generate(
            request_id=self.eid, prompt_ids=ids, sampling_params={**self.sampling, "max_tokens": max_tokens}
        )
        model_s = time.time() - t0
        merged, mask, logprobs = await self.ct_merge_assistant_token(
            ids, output.token_ids, mask, logprobs, assistant_logprobs=output.log_probs
        )
        self.ids, self.mask, self.logprobs = merged.token_ids, mask, logprobs
        steps = [output.extra_fields.get(k) for k in ("min_global_steps", "max_global_steps")]
        steps = [s for s in steps if s is not None]
        self.segment_steps += steps
        self.global_steps += steps
        finish = "length" if output.stop_reason == "length" else "stop"
        self.calls.append(
            {"prompt": len(ids), "completion": len(output.token_ids), "model_s": model_s, "finish": finish}
        )
        text = self.tokenizer.decode(output.token_ids, skip_special_tokens=True)
        self.messages = messages + [{"role": "assistant", "content": text}]
        return _completion(body, text, finish, len(ids), len(output.token_ids))


def _write_data(split_dir, out):
    import pandas as pd

    tasks_dir = os.path.join(split_dir, "tasks")
    # The Harbor server indexes a split's tasks by sorted directory name (openenv/harbor/tasks.py).
    names = sorted(n for n in os.listdir(tasks_dir) if not n.startswith("."))
    rows = [
        {
            "data_source": "termgrade",
            "prompt": [{"role": "user", "content": open(os.path.join(tasks_dir, n, "instruction.md")).read()}],
            "agent_name": "harbor",
            "reward_model": {"style": "rule", "ground_truth": ""},
            "extra_info": {"index": i, "task_index": i, "task": n},
        }
        for i, n in enumerate(names)
    ]
    pd.DataFrame(rows).to_parquet(out, index=False)
    print(f"{len(rows)} tasks -> {out}")


def _stub(port):
    app = web.Application()
    app.router.add_get("/v1/models", _models)
    app.router.add_post("/v1/chat/completions", _chat)
    web.run_app(app, host="127.0.0.1", port=port, access_log=None, print=None)


if __name__ == "__main__":
    if sys.argv[1] == "data":
        _write_data(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "stub":
        _stub(int(sys.argv[2]))
